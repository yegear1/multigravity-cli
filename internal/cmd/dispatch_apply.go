package cmd

import (
	"encoding/json"
	"fmt"
	"strings"

	"github.com/spf13/cobra"

	"github.com/ye-dev/multigravity-cli/internal/dispatch"
)

var (
	dpDryRun   bool
	dpNoPrune  bool
	dpThreeWay bool
)

func newDispatchApplyCmd() *cobra.Command {
	applySubCmd := &cobra.Command{
		Use:   "apply <task-id>",
		Short: "Apply inspected diff from an ephemeral worktree to the base repository",
		Long: `Apply the approved changes generated by a completed task's ephemeral worktree
to the base repository working tree, and prune the ephemeral worktree upon success.`,
		Args:              cobra.ExactArgs(1),
		ValidArgsFunction: taskArgsCompletion,
		RunE:              runDispatchApply,
	}
	applySubCmd.Flags().StringVar(&dpRunRepo, "repo", "", "Target git repository directory")
	applySubCmd.Flags().BoolVar(&dpDryRun, "dry-run", false, "Simulate patch application without modifying working tree")
	applySubCmd.Flags().BoolVar(&dpNoPrune, "no-prune", false, "Preserve ephemeral worktree and branch after application")
	applySubCmd.Flags().BoolVar(&dpThreeWay, "3way", false, "Attempt 3-way merge if patch does not apply cleanly")
	return applySubCmd
}

func runDispatchApply(cmd *cobra.Command, args []string) error {
	defer func() {
		dpRunRepo = ""
		dpDryRun = false
		dpNoPrune = false
		dpThreeWay = false
		dpJSON = false
	}()

	taskID := args[0]
	mgr := dispatch.GetDefaultTaskManager()

	opts := dispatch.ApplyOptions{
		RepoPath: dpRunRepo,
		DryRun:   dpDryRun,
		NoPrune:  dpNoPrune,
		ThreeWay: dpThreeWay,
	}

	result, err := mgr.ApplyTask(dpRunRepo, taskID, opts)
	if err != nil {
		return err
	}

	out := cmd.OutOrStdout()

	if dpJSON {
		enc := json.NewEncoder(out)
		enc.SetIndent("", "  ")
		return enc.Encode(result)
	}

	if result.DryRun {
		fmt.Fprintf(out, "%s [DRY RUN] Patch from task %s would apply cleanly to %s\n",
			dpCyan("●"), dpBold(result.TaskID), dpDim(result.BaseRepoPath))
		fmt.Fprintf(out, "  Files to modify: %d | Additions: %s | Deletions: %s\n",
			result.FilesApplied,
			dpGreen(fmt.Sprintf("+%d", result.Additions)),
			dpRed(fmt.Sprintf("-%d", result.Deletions)))
		if result.Structured != nil {
			for _, f := range result.Structured.Files {
				p := f.NewPath
				if p == "" {
					p = f.OldPath
				}
				if f.Binary {
					fmt.Fprintf(out, "    [%s] %s (binary)\n", strings.ToUpper(string(f.Status)), p)
				} else {
					fmt.Fprintf(out, "    [%s] %s (+%d, -%d)\n", strings.ToUpper(string(f.Status)), p, f.Additions, f.Deletions)
				}
			}
		}
		fmt.Fprintf(out, "\nNo files were modified. Worktree %s was preserved.\n", dpBold(result.WorktreeID))
		return nil
	}

	fmt.Fprintf(out, "%s Patch from task %s applied cleanly to %s\n",
		dpGreen("✓"), dpBold(result.TaskID), dpDim(result.BaseRepoPath))
	fmt.Fprintf(out, "  Files modified:  %d | Additions: %s | Deletions: %s\n",
		result.FilesApplied,
		dpGreen(fmt.Sprintf("+%d", result.Additions)),
		dpRed(fmt.Sprintf("-%d", result.Deletions)))
	if result.Structured != nil {
		for _, f := range result.Structured.Files {
			p := f.NewPath
			if p == "" {
				p = f.OldPath
			}
			if f.Binary {
				fmt.Fprintf(out, "    [%s] %s (binary)\n", strings.ToUpper(string(f.Status)), p)
			} else {
				fmt.Fprintf(out, "    [%s] %s (+%d, -%d)\n", strings.ToUpper(string(f.Status)), p, f.Additions, f.Deletions)
			}
		}
	}

	if result.Pruned {
		fmt.Fprintf(out, "\nEphemeral worktree %s and branch were cleanly removed.\n", dpBold(result.WorktreeID))
	} else {
		fmt.Fprintf(out, "\nEphemeral worktree %s preserved (--no-prune).\n", dpBold(result.WorktreeID))
	}
	return nil
}
